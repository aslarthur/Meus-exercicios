# ===================== RESUMO =====================

# --- Atribuição e comparação ---
# =    -> atribuir um valor a uma variável
# ==   -> compara se dois valores são iguais
# !=   -> diferente de
# >=   -> maior ou igual
# <=   -> menor ou igual

# --- Tipos de dados ---
# int      -> número inteiro
# float    -> número com casas decimais
# str      -> texto (string)
# boolean  -> True ou False (Verdadeiro ou Falso)

# --- Estruturas de controle ---
# if     -> se
# else   -> se não
# while  -> enquanto

# --- Entrada e saída ---
# print          -> imprimir algo na tela
# input          -> fazer o usuário digitar alguma informação
# \n             -> quebra de linha
# end=" "        -> continua na mesma linha (não pula linha após o print)
# .format()      -> insere valores dentro de uma string e os formata
# {:.2f}         -> limita o resultado a 2 casas decimais

# --- Bibliotecas ---
# import math            -> importa a biblioteca "math" (matemática)
# from math import sqrt  -> importa só a função de raiz quadrada da "math"

# --- Operadores aritméticos ---
# +   -> adição
# -   -> subtração
# *   -> multiplicação
# /   -> divisão normal
# //  -> divisão inteira
# **  -> potenciação
# % -> resto da divisão

# --- Ordem de precedência (do mais alto pro mais baixo) 
# 1: ()          -> Parênteses
# 2: **          -> Potenciação
# 3: *, /, //, % -> Multiplicação, divisão, divisão inteira, módulo
# 4: +, -        -> Adição e subtração